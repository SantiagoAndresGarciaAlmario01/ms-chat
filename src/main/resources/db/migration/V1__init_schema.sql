-- ms-chat · esquema inicial (Sprint 1)
-- Database per Service: publicacion_id, comprador_id, vendedor_id y autor_id son ids de otros
-- microservicios, por eso no tienen llaves foráneas.

CREATE TABLE conversaciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publicacion_id  BIGINT       NOT NULL,
    prenda_nombre   VARCHAR(200),
    comprador_id    BIGINT       NOT NULL,
    vendedor_id     BIGINT       NOT NULL,
    estado          VARCHAR(20)  NOT NULL,
    fecha_creacion  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_conversacion_publicacion_comprador UNIQUE (publicacion_id, comprador_id),
    CONSTRAINT ck_conversacion_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT ck_conversacion_participantes CHECK (comprador_id <> vendedor_id)
);

CREATE INDEX ix_conversacion_comprador ON conversaciones (comprador_id);
CREATE INDEX ix_conversacion_vendedor ON conversaciones (vendedor_id);

CREATE TABLE mensajes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id  BIGINT        NOT NULL REFERENCES conversaciones (id),
    autor_id         BIGINT        NOT NULL,
    texto            VARCHAR(1000) NOT NULL,
    fecha_envio      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_mensaje_conversacion_fecha ON mensajes (conversacion_id, fecha_envio, id);
